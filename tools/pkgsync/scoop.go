package main

import (
	"bytes"
	"encoding/json"
	"strings"
)

type scoop struct{}

func (scoop) Name() string     { return "scoop" }
func (scoop) HasBuckets() bool { return true }
func (scoop) Available() bool  { return available("scoop") }

func (scoop) Snapshot() (Snapshot, error) {
	out, err := output("scoop", "export")
	if err != nil {
		return Snapshot{}, err
	}
	return parseScoopExport(out)
}

func parseScoopExport(out []byte) (Snapshot, error) {
	out = bytes.TrimPrefix(out, []byte("\xef\xbb\xbf"))

	// Field names differ in case between scoop versions; encoding/json
	// matches them case-insensitively. Version and Updated are not decoded.
	var exp struct {
		Buckets []struct{ Name string }
		Apps    []struct{ Name, Source, Info string }
	}
	if err := json.Unmarshal(out, &exp); err != nil {
		return Snapshot{}, err
	}

	var s Snapshot
	for _, b := range exp.Buckets {
		s.Buckets = append(s.Buckets, b.Name)
	}
	for _, a := range exp.Apps {
		// Info is empty for a plain install; anything else (global, failed,
		// ...) is surfaced as a warning and otherwise ignored. A hold is
		// deliberate, so it is not worth a warning.
		if info := withoutHold(a.Info); info != "" {
			s.Warnings = append(s.Warnings, a.Name+": "+info)
		}
		switch {
		case a.Source == "":
			// A failed install has no install info, hence no Source.
		case a.Source == "<auto-generated>" || strings.ContainsAny(a.Source, `/\:`):
			// Not from a bucket: a local manifest or a URL.
			s.External = append(s.External, a.Name)
		default:
			s.Packages = append(s.Packages, a.Name)
		}
	}
	return s, nil
}

func (scoop) InstallHints(d Diff) []string {
	var cmds []string
	for _, b := range d.DelBuckets {
		cmds = append(cmds, "scoop bucket add "+b)
	}
	if len(d.DelPkgs) > 0 {
		cmds = append(cmds, "scoop install "+strings.Join(d.DelPkgs, " "))
	}
	return cmds
}

// withoutHold drops "Held package" from a ", "-separated Info string.
func withoutHold(info string) string {
	var keep []string
	for _, p := range strings.Split(info, ", ") {
		if p != "" && p != "Held package" {
			keep = append(keep, p)
		}
	}
	return strings.Join(keep, ", ")
}
